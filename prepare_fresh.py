"""Safely reset only resources belonging to the WADe graduate demo.

Run with the web server STOPPED. Targets only localhost:4566 / localhost:4567
with dummy credentials; does not change/deploy AWS resources.

Without --apply, prints a read-only preview. With --apply, restores the
notification first, then removes demo generated objects and job histories.
Does not delete buckets, Lambda functions, SQS queues, DynamoDB tables,
other sample projects, or saved recovery backups.
"""
from __future__ import annotations

import argparse
import sys
from botocore.exceptions import ClientError

import queued_jobs
import trigger_lab

# These are the exact key namespaces generated by the web demo, not entire buckets.
OBJECT_PREFIXES = (
    (trigger_lab.INPUT_BUCKET, 'incoming/browser-'),
    (trigger_lab.OUTPUT_BUCKET, 'reports/browser-'),
    (queued_jobs.BUCKET, 'incoming/queued-'),
    (trigger_lab.OUTPUT_BUCKET, 'reports/queued-'),
)


def list_keys(s3, bucket, prefix):
    token = None
    while True:
        args = {'Bucket': bucket, 'Prefix': prefix, 'MaxKeys': 500}
        if token:
            args['ContinuationToken'] = token
        page = s3.list_objects_v2(**args)
        for item in page.get('Contents', []):
            key = item['Key']
            # Double-check keys: never let an emulator's faulty prefix search
            # delete something outside the project's exact namespace.
            if key.startswith(prefix):
                yield key
        token = page.get('NextContinuationToken')
        if not token:
            break


def list_job_ids(ddb):
    args = {'TableName': queued_jobs.TABLE, 'ProjectionExpression': 'jobId'}
    while True:
        page = ddb.scan(**args)
        for item in page.get('Items', []):
            jobid = item.get('jobId', {}).get('S')
            if jobid:
                yield jobid
        last = page.get('LastEvaluatedKey')
        if not last:
            break
        args['ExclusiveStartKey'] = last


def reset_emulator(name, apply):
    print(f'\n{name} — {queued_jobs.PORTS[name]}')
    snap = trigger_lab.state(name)
    if not snap['connected']:
        if not snap['backupSaved']:
            raise RuntimeError('S3 notification DISCONNECTED and backup missing. Cannot safely clean. Restore it manually first.')
        print('  Notification disconnected; saved backup found. Apply will restore first.')
    else:
        print('  S3 notification connected.')
    c = queued_jobs.clients(name)
    s3, ddb, sqs = c['s3'], c['dynamodb'], c['sqs']

    # Do not create resources during the preview; report absent optional queue/table.
    try:
        queue_url = queued_jobs.queue_url(sqs, name)
    except ClientError as exc:
        if exc.response.get('Error', {}).get('Code') in {'AWS.SimpleQueueService.NonExistentQueue', 'QueueDoesNotExist'}:
            queue_url = None
        else:
            raise
    try:
        ddb.describe_table(TableName=queued_jobs.TABLE)
        has_table = True
    except ClientError as exc:
        if exc.response.get('Error', {}).get('Code') == 'ResourceNotFoundException':
            has_table = False
        else:
            raise

    planned = {}
    for bucket, prefix in OBJECT_PREFIXES:
        keys = list(list_keys(s3, bucket, prefix))
        planned[(bucket, prefix)] = keys
        print(f'  {bucket}/{prefix}*: {len(keys)} object(s)')
    if has_table:
        ids = list(list_job_ids(ddb))
    else:
        ids = []
    print(f'  DynamoDB job history: {len(ids)} item(s)')
    print(f'  Dedicated SQS queue: {"present (messages will be purged)" if queue_url else "not yet created"}')
    print(f'  Trigger experiment objects: {"will be cleared by safe reset" if apply else "available to reset"}')
    if not apply:
        return

    # Safety order: repair notifications BEFORE deleting any objects.
    outcome = trigger_lab.reset(name)
    print(f'  Restored/verified notification; removed {outcome["removed"]} trigger-lab object(s).')
    # Purge before deleting the job ledger; otherwise a pending message could
    # be processed against a missing status item.
    if queue_url:
        sqs.purge_queue(QueueUrl=queue_url)
        print('  SQS queue purged (approximate counters may update later).')
    for (bucket, prefix), keys in planned.items():
        for key in keys:
            if not key.startswith(prefix):
                raise RuntimeError('Unexpected key escaped namespace guard')
            s3.delete_object(Bucket=bucket, Key=key)
        print(f'  Removed {len(keys)} object(s) from {bucket}/{prefix}*')
    for jobid in ids:
        ddb.delete_item(TableName=queued_jobs.TABLE, Key={'jobId': {'S': jobid}})
    print(f'  Removed {len(ids)} DynamoDB job item(s).')
    print('  Done. Lambda, bucket rules, queues and tables remain installed. Backups remain on disk.')


def main(argv=None):
    p = argparse.ArgumentParser(description='Reset only the locally generated WADe graduate-demo data.')
    p.add_argument('--emulator', choices=['FakeCloud', 'LocalStack', 'both'], default='both')
    p.add_argument('--apply', action='store_true', help='Perform the reset. Default is read-only preview.')
    a = p.parse_args(argv)
    print('Local-only graduate demo cleanup. Stop ui_server.py first. No Docker resources are deleted.')
    print('Mode:', 'APPLY' if a.apply else 'PREVIEW ONLY (nothing modified)')
    names = list(queued_jobs.PORTS) if a.emulator == 'both' else [a.emulator]
    errors = 0
    for name in names:
        try:
            reset_emulator(name, a.apply)
        except Exception as exc:
            errors += 1
            print(f'  STOPPED for {name}: {type(exc).__name__}: {exc}', file=sys.stderr)
    return 1 if errors else 0


if __name__ == '__main__':
    sys.exit(main())
